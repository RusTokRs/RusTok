import 'dart:io';

import 'package:rustok_i18n/rustok_i18n.dart';
import 'package:rustok_i18n/src/cli/i18n_cli.dart';
import 'package:test/test.dart';

class _Run {
  _Run(this.code, this.out, this.err);

  final int code;
  final List<String> out;
  final List<String> err;

  String get stdoutText => out.join('\n');
  String get stderrText => err.join('\n');
}

_Run _run(List<String> args) {
  final out = <String>[];
  final err = <String>[];
  final code = runI18nCli(args, out: out.add, err: err.add);
  return _Run(code, out, err);
}

const String _en = '''
welcome = Welcome
input = Search
    .placeholder = Type here
unread = { \$count ->
    [one] One message
   *[other] { \$count } messages
}
''';

const String _ru = '''
welcome = Добро пожаловать
input = Поиск
    .placeholder = Введите текст
unread = { \$count ->
    [one] Одно сообщение
   *[other] { \$count } сообщений
}
''';

/// Byte-exact expected output for the `emits a stable skeleton (golden)` test —
/// the generator must stay reproducible down to the indentation.
const String _golden = '''// Auto-generated by rustok_i18n typegen. DO NOT EDIT DIRECTLY.
import 'package:rustok_i18n/rustok_i18n.dart';

class M {
  const M(this._messages, {this.locale});

  final UiMessages _messages;
  final String? locale;

  /// Greets the user.
  String greet({required dynamic name}) => _messages.t(
        'greet',
        locale: locale,
        args: {'name': name},
      );

  String countLabel({required dynamic count}) => _messages.t(
        'count-label',
        locale: locale,
        args: {'count': count},
      );

  String countLabelAriaLabel({required dynamic count}) => _messages.tAttr(
        'count-label',
        'aria-label',
        locale: locale,
        args: {'count': count},
      );

}
''';

void main() {
  late Directory tmp;

  setUp(() {
    tmp = Directory.systemTemp.createTempSync('rustok_i18n_cli_');
  });

  tearDown(() {
    if (tmp.existsSync()) tmp.deleteSync(recursive: true);
  });

  void writeFile(String name, String content) {
    File('${tmp.path}/$name').writeAsStringSync(content);
  }

  String path(String name) => '${tmp.path}/$name';

  group('check', () {
    test('passes when every locale matches the baseline', () {
      writeFile('en.ftl', _en);
      writeFile('ru.ftl', _ru);

      final result = _run(['check', '--dir', tmp.path, '--baseline', 'en']);

      expect(result.code, exitOk);
      expect(result.stdoutText, contains('[PASS] ru'));
      expect(result.stdoutText, contains('All locales are in full parity!'));
    });

    test('reports missing and extra keys', () {
      writeFile('en.ftl', _en);
      writeFile(
        'ru.ftl',
        _ru.replaceFirst('welcome = Добро пожаловать\n', '') +
            'extra-key = Лишнее\n',
      );

      final result = _run(['check', '--dir', tmp.path]);

      expect(result.code, exitFailure);
      expect(result.stdoutText, contains('Missing keys (1): welcome'));
      expect(result.stdoutText, contains('Extra keys (1): extra-key'));
    });

    test('reports a missing attribute even when the message exists', () {
      writeFile('en.ftl', _en);
      writeFile(
        'ru.ftl',
        _ru.replaceFirst('    .placeholder = Введите текст\n', ''),
      );

      final result = _run(['check', '--dir', tmp.path]);

      expect(result.code, exitFailure);
      expect(result.stdoutText,
          contains('Message "input" is missing attributes: placeholder'));
    });

    test('reports an attribute the baseline does not define', () {
      writeFile('en.ftl', _en);
      writeFile(
        'ru.ftl',
        _ru.replaceFirst(
          '    .placeholder = Введите текст\n',
          '    .placeholder = Введите текст\n    .hint = Подсказка\n',
        ),
      );

      final result = _run(['check', '--dir', tmp.path]);

      expect(result.code, exitFailure);
      expect(result.stdoutText,
          contains('Message "input" has extra attributes: hint'));
    });

    test('reports parser diagnostics in a locale file', () {
      writeFile('en.ftl', _en);
      writeFile('ru.ftl', '$_ru\nbroken line without equals\n');

      final result = _run(['check', '--dir', tmp.path]);

      expect(result.code, exitFailure);
      expect(result.stdoutText, contains('Junk'));
    });

    test('fails when the baseline file is absent', () {
      writeFile('ru.ftl', _ru);

      final result = _run(['check', '--dir', tmp.path, '--baseline', 'en']);

      expect(result.code, exitFailure);
      expect(result.stderrText, contains('Baseline file "en.ftl" not found'));
    });

    test('fails for a missing directory', () {
      final result = _run(['check', '--dir', path('nope')]);

      expect(result.code, exitFailure);
      expect(result.stderrText, contains('does not exist'));
    });

    test('warns and succeeds when there are no .ftl files', () {
      final result = _run(['check', '--dir', tmp.path]);

      expect(result.code, exitOk);
      expect(result.stdoutText, contains('No .ftl files found'));
    });
  });

  group('typegen', () {
    test('generates typed getters and parameterised methods', () {
      writeFile('en.ftl', _en);
      final output = path('messages.g.dart');

      final result = _run([
        'typegen',
        '--input', path('en.ftl'),
        '--output', output,
        '--className', 'AppMessages',
      ]);

      expect(result.code, exitOk);
      final code = File(output).readAsStringSync();
      expect(code, contains('class AppMessages {'));
      expect(code, contains('String get welcome => _messages.t('));
      expect(code, contains('String unread({required dynamic count}) => _messages.t('));
      expect(code, contains("args: {'count': count},"));
    });

    test('generates a parameter for each variable used in a message', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource('a = { \$x } and { \$y }\n');
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(source!.code, contains('String a({required dynamic x, required dynamic y})'));
      expect(source.generated, 1);
    });

    test('rejects an invalid class name', () {
      writeFile('en.ftl', _en);

      final result = _run([
        'typegen',
        '--input', path('en.ftl'),
        '--output', path('out.dart'),
        '--className', 'lowerCase',
      ]);

      expect(result.code, exitFailure);
      expect(File(path('out.dart')).existsSync(), isFalse);
    });

    test('fails when two keys map to the same Dart member', () {
      writeFile('dup.ftl', 'a-b = one\na_b = two\n');

      final result = _run([
        'typegen',
        '--input', path('dup.ftl'),
        '--output', path('out.dart'),
      ]);

      expect(result.code, exitFailure);
      expect(result.stderrText, contains('both map to Dart member "aB"'));
    });

    test('fails on invalid input without writing output', () {
      writeFile('bad.ftl', 'broken line without equals\n');

      final result = _run([
        'typegen',
        '--input', path('bad.ftl'),
        '--output', path('out.dart'),
      ]);

      expect(result.code, exitFailure);
      expect(File(path('out.dart')).existsSync(), isFalse);
    });

    test('emits a stable skeleton (golden)', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource(
          '# Greets the user.\n'
          'greet = Hello, { \$name }!\n'
          '\n'
          'count-label = { \$count } items\n'
          '    .aria-label = { \$count } items, list\n',
        );
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(source!.code, _golden);
      expect(source.generated, 3);
    });

    test('renames members that collide with the class API or with Object', () {
      writeFile(
        'api.ftl',
        'locale = Locale\n'
        'to-string = Text\n'
        'hash-code = Number\n'
        'runtime-type = Type\n'
        'no-such-method = Missing\n',
      );

      final result = _run([
        'typegen',
        '--input', path('api.ftl'),
        '--output', path('out.dart'),
      ]);

      expect(result.code, exitOk);
      final code = File(path('out.dart')).readAsStringSync();
      expect(code, contains('String get localeMessage => _messages.t('));
      expect(code, contains('String get toStringMessage => _messages.t('));
      expect(code, contains('String get hashCodeMessage => _messages.t('));
      expect(code, contains('String get runtimeTypeMessage => _messages.t('));
      expect(code, contains('String get noSuchMethodMessage => _messages.t('));
      // The body still passes the *field*, never a parameter, as the locale.
      expect(code, contains('locale: locale,'));
      expect(code, isNot(contains('String get locale =>')));
    });

    test('an attribute whose member would clash with Object is renamed too', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource('to = To\n    .string = Text\n');
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(source!.code,
          contains('String get toStringMessage => _messages.tAttr('));
      expect(source.code, contains("        'string',"));
    });

    test('a "locale" variable becomes localeArg and cannot shadow the field', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource('region = Region: { \$locale }\n');
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(
        source!.code,
        contains('String region({required dynamic localeArg}) => _messages.t('),
      );
      expect(source.code, contains("args: {'locale': localeArg},"));
      // One `locale:` argument only — the instance field passed by the getter.
      expect(source.code.split('locale: locale,').length - 1, 1);
    });

    test('parameters cover the variables of referenced messages', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource(
          'greeting = Hello { \$name }\n'
          'wrapped = { greeting }\n'
          'listed = { greeting } and { greeting }\n'
          'plain = No variables\n',
        );
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(source!.generated, 4);
      expect(source.code, contains('String wrapped({required dynamic name})'));
      expect(source.code, contains('String listed({required dynamic name})'));
      expect(source.code, contains("args: {'name': name},"));
      expect(source.code, contains('String get plain => _messages.t('));
    });

    test('reference cycles neither loop nor widen the signature', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource('a = { b }\nb = { a }\n');
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(source!.generated, 2);
      expect(source.code, contains('String get a => _messages.t('));
      expect(source.code, contains('String get b => _messages.t('));
    });

    test('an attribute-only message yields attribute getters but no value one', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)
        ..addSource('label =\n    .title = Title\n    .hint = Hint\n');
      final source = generateTypedMessages(bundle, className: 'M');

      expect(source, isNotNull);
      expect(source!.generated, 2);
      expect(source.code, contains('String get labelTitle => _messages.tAttr('));
      expect(source.code, contains('String get labelHint => _messages.tAttr('));
      expect(source.code, isNot(contains('String get label =>')));

      writeFile('attr.ftl', 'label =\n    .title = Title\n');
      final result = _run([
        'typegen',
        '--input', path('attr.ftl'),
        '--output', path('out.dart'),
      ]);
      expect(result.code, exitOk);
      expect(result.stdoutText, contains('accessors: 1, keys: 1'));
      expect(result.stdoutText, contains('attribute getters only'));
    });

    test('rejects a class name the generated file already uses', () {
      writeFile('en.ftl', _en);

      final result = _run([
        'typegen',
        '--input', path('en.ftl'),
        '--output', path('out.dart'),
        '--className', 'UiMessages',
      ]);

      expect(result.code, exitFailure);
      expect(result.stderrText, contains('already the name of a type'));
      expect(File(path('out.dart')).existsSync(), isFalse);
    });
  });

  group('Typegen resolver argument contract', () {
    test('direct generator validates class names before emitting source', () {
      final bundle = FluentBundle(locale: 'en')..addSource('hello = Hi');
      for (final name in ['lowerCase', 'Bad-Name', 'String', 'UiMessages']) {
        final errors = <String>[];
        expect(generateTypedMessages(bundle, className: name, writeErr: errors.add),
            isNull, reason: name);
        expect(errors, hasLength(1), reason: name);
      }
    });

    test('CLI rejects String without overwriting an existing output', () {
      writeFile('en.ftl', 'hello = Hi');
      writeFile('keep.dart', 'keep this file');
      final result = _run([
        'typegen', '--input', path('en.ftl'), '--output', path('keep.dart'),
        '--className', 'String',
      ]);
      expect(result.code, exitFailure);
      expect(result.stderrText, contains('already the name of a type'));
      expect(File(path('keep.dart')).readAsStringSync(), 'keep this file');
    });

    test('ignored term positional arguments do not become required parameters', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)..addSource(
        '-brand = Brand\nmessage = { -brand(\$unused) }\n');
      expect(bundle.diagnostics, isEmpty);
      expect(bundle.format('message'), 'Brand');
      final source = generateTypedMessages(bundle, className: 'M');
      expect(source, isNotNull);
      expect(source!.code, contains('String get message =>'));
      expect(source.code, isNot(contains('required dynamic unused')));
    });

    test('only the first function argument contributes caller variables', () {
      final bundle = FluentBundle(locale: 'en', useIsolating: false)..addSource(
        'number = { NUMBER(\$value, \$unused) }\n'
        'fallback = { UNKNOWN(\$text, \$ignored) }\n');
      expect(bundle.diagnostics, isEmpty);
      expect(bundle.format('number', args: {'value': 3}), '3');
      expect(bundle.format('fallback', args: {'text': 'ok'}), 'ok');
      final source = generateTypedMessages(bundle, className: 'M');
      expect(source, isNotNull);
      expect(source!.code, contains('number({required dynamic value})'));
      expect(source.code, contains('fallback({required dynamic text})'));
      expect(source.code, isNot(contains('required dynamic unused')));
      expect(source.code, isNot(contains('required dynamic ignored')));
    });
  });

  group('argument handling', () {
    test('no arguments prints usage and returns the usage code', () {
      final result = _run([]);

      expect(result.code, exitUsage);
      expect(result.stdoutText, contains('Usage:'));
    });

    test('unknown command returns the usage code', () {
      final result = _run(['frobnicate']);

      expect(result.code, exitUsage);
    });

    test('missing mandatory option returns the usage code', () {
      final result = _run(['check']);

      expect(result.code, exitUsage);
      expect(result.stderrText, contains('Error:'));
    });
  });
}

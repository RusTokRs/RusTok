#!/usr/bin/env python3
"""Generate the complete CLDR 48.2 likely-subtags table from a local input.

Inputs: cldr-core@48.2.0/supplemental/likelySubtags.json and
scriptMetadata.json (npm package). Both hashes are pinned.
No network access or runtime dependency. --check compares without writing.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

SOURCE_SHA256 = '38345946ad457213fb39e9645ab50f36b61681bf674b2eef2979a3b58d04afc8'
SCRIPT_SHA256 = '9160c07c87f58495f57076c88231f63c1c062672991822671c9e99697b5e5cda'
DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / 'packages/rustok_i18n/lib/src/locale/likely_subtags_data.dart'


def render(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError('Input is not the pinned cldr-core@48.2.0 likelySubtags.json')
    data = json.loads(source)['supplemental']['likelySubtags']
    lines = [
        '// Generated by tooling/scripts/gen_likely_subtags.py. Do not edit.',
        '// Source: cldr-core@48.2.0/supplemental/likelySubtags.json',
        '// Unicode-3.0; see the package LICENSE.',
        f'// Source SHA-256: {SOURCE_SHA256}',
        "part of 'likely_subtags.dart';", '',
        'const Map<String, String> _likelySubtags = {',
    ]
    for key, value in sorted(data.items()):
        if not re.fullmatch(r'[A-Za-z0-9-]+', key) or not re.fullmatch(r'[a-z]{2,8}-[A-Z][a-z]{3}-(?:[A-Z]{2}|[0-9]{3})', value):
            raise ValueError(f'Invalid likely subtag: {key!r}: {value!r}')
        lines.append(f"  '{key}': '{value}',")
    return '\n'.join(lines + ['};', ''])


def render_scripts(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != SCRIPT_SHA256:
        raise ValueError('Input is not pinned cldr-core@48.2.0 scriptMetadata.json')
    data = json.loads(source)['scriptMetadata']
    scripts = sorted(k for k, v in data.items() if v['rtl'] == 'YES')
    if any(not re.fullmatch(r'[A-Z][a-z]{3}', k) for k in scripts):
        raise ValueError('Invalid script code')
    return '\n'.join([
        '// Generated by tooling/scripts/gen_likely_subtags.py. Do not edit.',
        '// cldr-core@48.2.0/scriptMetadata.json; Unicode-3.0, see LICENSE.',
        f'// Source SHA-256: {SCRIPT_SHA256}',
        "part of 'text_direction.dart';", '',
        'const Set<String> _rtlScripts = {',
        *(f"  '{k}'," for k in scripts), '};', '',
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', required=True, type=Path)
    parser.add_argument('--scripts', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    script_output = args.output.with_name('text_direction_data.dart')
    targets = {args.output.resolve(), script_output.resolve()}
    inputs = {args.input.resolve(), args.scripts.resolve()}
    if len(targets) != 2:
        parser.error('Output files must have distinct paths')
    if targets & inputs:
        parser.error('Output files must not overwrite input data')
    outputs = {
        args.output: render(args.input.read_bytes()),
        script_output: render_scripts(args.scripts.read_bytes()),
    }
    for output, result in outputs.items():
        if args.check:
            if not output.exists() or output.read_text(encoding='utf-8') != result:
                raise SystemExit(f'Generated table differs: {output}')
        else:
            output.write_text(result, encoding='utf-8')


if __name__ == '__main__':
    main()

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Public device cryptographic identity registered by a user device.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DeviceKey {
    /// Unique client device identifier (e.g. mobile install instance or browser ID).
    pub device_id: String,
    /// Owner user ID.
    pub user_id: Uuid,
    /// Master Ed25519 public signing identity key (Base64).
    pub identity_key: String,
    /// Primary Curve25519 public key for Diffie-Hellman key exchange.
    pub curve25519_key: String,
    /// Cryptographic signature over keys generated by the identity key.
    pub signature: String,
    /// Registration timestamp.
    pub created_at: DateTime<Utc>,
}

/// A consumable One-Time Prekey (OTK) for asynchronous X3DH initial session establishment.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct OneTimePrekey {
    /// Key identifier inside the device's prekey pool.
    pub key_id: String,
    /// Owning device identifier.
    pub device_id: String,
    /// Base64-encoded Curve25519 public prekey material.
    pub key_material: String,
    /// Cryptographic signature over the prekey.
    pub signature: Option<String>,
    /// Whether this one-time key has already been consumed by an initiator.
    pub consumed: bool,
}

/// Complete prekey bundle returned when initiating an encrypted 1-on-1 session with a peer.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PrekeyBundle {
    pub user_id: Uuid,
    pub device_id: String,
    pub identity_key: String,
    pub curve25519_key: String,
    pub one_time_prekey: Option<OneTimePrekey>,
}

/// Request to register device identity and publish initial pool of one-time prekeys.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UploadDeviceKeysInput {
    pub device_id: String,
    pub identity_key: String,
    pub curve25519_key: String,
    pub signature: String,
    pub one_time_prekeys: Vec<OneTimePrekeyInput>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OneTimePrekeyInput {
    pub key_id: String,
    pub key_material: String,
    pub signature: Option<String>,
}

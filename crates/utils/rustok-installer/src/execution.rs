//! Typed input and output contracts for an install-apply executor.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use thiserror::Error;
use uuid::Uuid;

#[cfg(feature = "host-runtime")]
use crate::InstallStep;
use crate::{InstallPlan, InstallReceipt, InstallState};

/// Host-selected execution options for one install apply operation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallApplyOptions {
    /// Host-issued stable session identity. HTTP jobs bind this before the
    /// worker starts so the session remains discoverable across process loss.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session_id: Option<Uuid>,
    /// Host-issued, unique owner identity for this execution attempt.
    pub lock_owner: String,
    /// Lease duration in seconds; accepted range is 1 through 86,400. Expiry alone
    /// does not release an unfinished session from global installer admission.
    pub lock_ttl_secs: i64,
    pub pg_admin_url: Option<String>,
    /// Host-selected Ed25519 authority for a signed fresh-target distribution
    /// receipt. This value is deliberately skipped by transport
    /// serialization: HTTP adapters must resolve it from host configuration,
    /// while a local CLI may bind its explicitly selected key.
    #[serde(skip)]
    pub bootstrap_public_key_base64: Option<String>,
}

pub const DEFAULT_INSTALL_LOCK_TTL_SECS: i64 = 900;
pub const MAX_INSTALL_LOCK_TTL_SECS: i64 = 86_400;

/// Returns whether a requested installer lease duration is within the
/// supported range. Keeping this bounded prevents timestamp overflow and
/// prevents operators from creating effectively permanent stale leases.
#[must_use]
pub const fn is_valid_install_lock_ttl_secs(ttl_secs: i64) -> bool {
    ttl_secs >= 1 && ttl_secs <= MAX_INSTALL_LOCK_TTL_SECS
}

/// Build a bounded owner token for one installer execution attempt.
///
/// The optional label is diagnostic only. The attempt ID must be freshly
/// generated by the trusted adapter for every attempt; a stable label or
/// session ID alone is not a safe lease owner across replicas or retries.
/// The result fits the install_sessions.lock_owner VARCHAR(128) column.
pub fn build_install_lock_owner(
    requested_label: Option<&str>,
    session_id: Option<Uuid>,
    attempt_id: Uuid,
) -> String {
    let normalized_label = requested_label
        .unwrap_or("installer")
        .chars()
        .filter(|character| {
            character.is_ascii_alphanumeric() || matches!(*character, '-' | '_')
        })
        .take(24)
        .collect::<String>();
    let label = if normalized_label.is_empty() {
        "installer"
    } else {
        normalized_label.as_str()
    };

    match session_id {
        Some(session_id) => format!("{label}:{session_id}:{attempt_id}"),
        None => format!("{label}:{attempt_id}"),
    }
}

impl Default for InstallApplyOptions {
    fn default() -> Self {
        Self {
            session_id: None,
            lock_owner: build_install_lock_owner(Some("installer"), None, Uuid::new_v4()),
            lock_ttl_secs: DEFAULT_INSTALL_LOCK_TTL_SECS,
            pg_admin_url: None,
            bootstrap_public_key_base64: None,
        }
    }
}

/// Durable result of a completed install apply operation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallApplyOutput {
    pub status: String,
    pub session_id: Uuid,
    pub tenant_id: Option<Uuid>,
    pub lock_owner: Option<String>,
    pub lock_expires_at: Option<DateTime<Utc>>,
    pub preflight_receipt_id: Uuid,
    pub preflight_receipt_checksum: String,
    pub config_receipt_id: Uuid,
    pub config_receipt_checksum: String,
    pub database_receipt_id: Uuid,
    pub database_receipt_checksum: String,
    pub migrate_receipt_id: Uuid,
    pub migrate_receipt_checksum: String,
    pub seed_receipt_id: Uuid,
    pub seed_receipt_checksum: String,
    pub admin_receipt_id: Uuid,
    pub admin_receipt_checksum: String,
    pub verify_receipt_id: Uuid,
    pub verify_receipt_checksum: String,
    pub finalize_receipt_id: Uuid,
    pub finalize_receipt_checksum: String,
    pub deployment_receipt: crate::InstallDistributionDeploymentReceipt,
    pub next: Option<String>,
}

/// Boundary implemented by a host-specific installer runtime.
#[async_trait::async_trait]
pub trait InstallExecutor: Send + Sync {
    async fn apply(
        &self,
        plan: InstallPlan,
        options: InstallApplyOptions,
    ) -> Result<InstallApplyOutput, InstallExecutionError>;
}

/// Durable installer-session projection independent of a persistence backend.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallSessionRecord {
    pub id: Uuid,
    pub tenant_id: Option<Uuid>,
    pub status: String,
    /// Monotonically increasing fencing generation assigned by the durable owner.
    pub attempt_generation: i64,
    pub lock_owner: Option<String>,
    pub lock_expires_at: Option<DateTime<Utc>>,
}

/// Durable receipt identity returned by a persistence adapter.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallReceiptRecord {
    pub id: Uuid,
    pub input_checksum: String,
}

/// Result of the database-readiness stage, retaining an adapter-private runtime
/// handle for the later schema, seed, admin and verification stages.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallDatabaseReady<R> {
    #[serde(skip)]
    pub runtime: R,
    pub database_name: Option<String>,
    pub created_database: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallSeedOutcome {
    pub tenant_id: Uuid,
    pub tenant_slug: String,
    pub tenant_created: bool,
    pub enabled_modules: Vec<String>,
    pub disabled_modules: Vec<String>,
    pub demo_customer_created: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallAdminOutcome {
    pub user_id: Uuid,
    pub email: String,
    pub created: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InstallVerificationOutcome {
    pub tenant_id: Uuid,
    pub tenant_slug: String,
    pub admin_user_id: Uuid,
    pub enabled_modules: Vec<String>,
}

/// Database readiness boundary. The adapter owns database-driver selection and
/// optional database creation; orchestration remains framework independent.
#[async_trait::async_trait]
pub trait InstallDatabasePort: Send + Sync {
    type Runtime: Send + Sync;

    async fn prepare_database(
        &self,
        plan: &InstallPlan,
        database_url: &str,
        options: &InstallApplyOptions,
    ) -> Result<InstallDatabaseReady<Self::Runtime>, InstallExecutionError>;
}

#[async_trait::async_trait]
pub trait InstallSchemaPort<R>: Send + Sync {
    /// Applies only the installer and release-owner schema required to create
    /// the durable operation and import a signed base distribution.
    async fn apply_owner_schema(&self, runtime: &R) -> Result<(), InstallExecutionError>;

    /// Applies the remaining canonical schema after the base distribution is
    /// durably owned by `rustok-modules`.
    async fn apply_remaining_schema(&self, runtime: &R) -> Result<(), InstallExecutionError>;
}

#[async_trait::async_trait]
pub trait InstallBootstrapPort<R>: Send + Sync {
    async fn import_base_distribution(
        &self,
        runtime: &R,
        plan: &InstallPlan,
        public_key_base64: Option<&str>,
    ) -> Result<
        Option<rustok_modules::ModuleStaticDistributionBootstrapImportReceipt>,
        InstallExecutionError,
    >;
}

#[async_trait::async_trait]
pub trait InstallPersistencePort<R>: Send + Sync {
    async fn create_session(
        &self,
        runtime: &R,
        session_id: Uuid,
        plan: &InstallPlan,
    ) -> Result<InstallSessionRecord, InstallExecutionError>;
    async fn acquire_lock(
        &self,
        runtime: &R,
        session: InstallSessionRecord,
        owner: &str,
        ttl_secs: i64,
    ) -> Result<InstallSessionRecord, InstallExecutionError>;
    async fn record_receipt(
        &self,
        runtime: &R,
        session: &InstallSessionRecord,
        receipt: &InstallReceipt,
    ) -> Result<InstallReceiptRecord, InstallExecutionError>;
    async fn set_state(
        &self,
        runtime: &R,
        session: &InstallSessionRecord,
        state: InstallState,
    ) -> Result<InstallSessionRecord, InstallExecutionError>;
    async fn set_tenant_id(
        &self,
        runtime: &R,
        session: &InstallSessionRecord,
        tenant_id: Uuid,
    ) -> Result<InstallSessionRecord, InstallExecutionError>;
}

#[async_trait::async_trait]
pub trait InstallSeedPort<R>: Send + Sync {
    async fn apply_seed(
        &self,
        runtime: &R,
        plan: &InstallPlan,
    ) -> Result<InstallSeedOutcome, InstallExecutionError>;
}

#[async_trait::async_trait]
pub trait InstallAdminPort<R>: Send + Sync {
    async fn provision_admin(
        &self,
        runtime: &R,
        plan: &InstallPlan,
        tenant_id: Uuid,
        password: &str,
    ) -> Result<InstallAdminOutcome, InstallExecutionError>;
}

#[async_trait::async_trait]
pub trait InstallVerificationPort<R>: Send + Sync {
    async fn verify_installation(
        &self,
        runtime: &R,
        plan: &InstallPlan,
        tenant_id: Uuid,
    ) -> Result<InstallVerificationOutcome, InstallExecutionError>;
}

/// Executes the canonical installer state machine through host-provided stage
/// ports. HTTP and CLI adapters must invoke this function rather than duplicate
/// stage ordering, state transitions, or receipt construction.
#[cfg(feature = "host-runtime")]
pub async fn execute_install_apply<P>(
    ports: &P,
    plan: InstallPlan,
    options: InstallApplyOptions,
) -> Result<InstallApplyOutput, InstallExecutionError>
where
    P: InstallDatabasePort
        + InstallSchemaPort<P::Runtime>
        + InstallBootstrapPort<P::Runtime>
        + InstallPersistencePort<P::Runtime>
        + InstallSeedPort<P::Runtime>
        + InstallAdminPort<P::Runtime>
        + InstallVerificationPort<P::Runtime>
        + crate::InstallDeploymentPort<P::Runtime>,
{
    if !is_valid_install_lock_ttl_secs(options.lock_ttl_secs) {
        return Err(InstallExecutionError::new(format!(
            "installer lock TTL must be between 1 and {MAX_INSTALL_LOCK_TTL_SECS} seconds"
        )));
    }

    let report = crate::evaluate_preflight_with_deployment(
        &plan,
        crate::InstallDeploymentPort::supports_distribution_deployment(ports),
    );
    if !report.passed() {
        return Err(InstallExecutionError::new("installer preflight failed"));
    }
    let invocation_dir = std::env::current_dir().map_err(|error| {
        InstallExecutionError::new(format!(
            "failed to resolve installer invocation directory: {error}"
        ))
    })?;
    let layout = crate::InstanceLayout::resolve(plan.placement.clone(), invocation_dir)
        .map_err(|error| InstallExecutionError::new(error.to_string()))?;
    let layout_preparation = crate::prepare_instance_layout(&layout)
        .map_err(|error| InstallExecutionError::new(error.to_string()))?;
    let session_id = options.session_id.unwrap_or_else(Uuid::new_v4);
    if session_id.is_nil() {
        return Err(InstallExecutionError::new(
            "installer session ID must not be nil",
        ));
    }
    let database_url = crate::resolve_local_secret_value(&plan.database.url, "database URL")
        .map_err(|error| InstallExecutionError::new(error.to_string()))?;
    let database = ports
        .prepare_database(&plan, &database_url, &options)
        .await?;
    ports.apply_owner_schema(&database.runtime).await?;
    let snapshot = crate::redact_install_plan(&plan);
    let mut session = ports
        .create_session(&database.runtime, session_id, &plan)
        .await?;
    session = ports
        .acquire_lock(
            &database.runtime,
            session,
            &options.lock_owner,
            options.lock_ttl_secs,
        )
        .await?;
    let bootstrap_import = match ports
        .import_base_distribution(
            &database.runtime,
            &plan,
            options.bootstrap_public_key_base64.as_deref(),
        )
        .await
    {
        Ok(import) => import,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::FreshInstallCleaned,
                    error,
                )
                .await,
            );
        }
    };
    if let Err(error) = ports.apply_remaining_schema(&database.runtime).await {
        return Err(
            persist_failure_state(
                ports,
                &database.runtime,
                &session,
                InstallState::FreshInstallCleaned,
                error,
            )
            .await,
        );
    }

    let preflight = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Preflight,
        &snapshot,
        serde_json::json!({
            "report": report,
            "mode": "apply",
            "note": "preflight receipt recorded after owner-schema bootstrap and base-distribution import",
            "base_distribution_import": bootstrap_import
        }),
    )
    .await?;
    session = ports
        .set_state(&database.runtime, &session, InstallState::PreflightPassed)
        .await?;
    let config = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Config,
        &snapshot,
        serde_json::json!({
            "source": "installer",
            "secrets_mode": plan.secrets_mode,
            "redacted": true,
            "instance_layout": layout_preparation
        }),
    )
    .await?;
    session = ports
        .set_state(&database.runtime, &session, InstallState::ConfigPrepared)
        .await?;
    let database_receipt = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Database,
        &snapshot,
        serde_json::json!({
            "database_engine": plan.database.engine,
            "database_name": database.database_name,
            "create_if_missing": plan.database.create_if_missing,
            "created_database": database.created_database,
            "checked": true
        }),
    )
    .await?;
    session = ports
        .set_state(&database.runtime, &session, InstallState::DatabaseReady)
        .await?;
    let migrate = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Migrate,
        &snapshot,
        serde_json::json!({
            "migrator": "rustok-migrations::Migrator",
            "limit": null,
            "applied": "owner_schema_then_base_distribution_import_then_remaining_schema"
        }),
    )
    .await?;
    session = ports
        .set_state(&database.runtime, &session, InstallState::SchemaApplied)
        .await?;

    // --- Post-Schema Durable Boundary: Failures require recovery rather than fresh-install cleanup ---
    let seed_outcome = match ports.apply_seed(&database.runtime, &plan).await {
        Ok(outcome) => outcome,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::RecoveryRequired,
                    error,
                )
                .await,
            );
        }
    };
    session = ports
        .set_tenant_id(&database.runtime, &session, seed_outcome.tenant_id)
        .await?;
    let seed = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Seed,
        &snapshot,
        serde_json::json!({
            "seed_profile": plan.seed_profile,
            "tenant_id": seed_outcome.tenant_id,
            "tenant_slug": seed_outcome.tenant_slug,
            "tenant_created": seed_outcome.tenant_created,
            "enabled_modules": seed_outcome.enabled_modules,
            "disabled_modules": seed_outcome.disabled_modules,
            "demo_customer_created": seed_outcome.demo_customer_created
        }),
    )
    .await?;
    session = ports
        .set_state(&database.runtime, &session, InstallState::SeedApplied)
        .await?;
    let password = match crate::resolve_local_secret_value(&plan.admin.password, "admin password") {
        Ok(pw) => pw,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::RecoveryRequired,
                    InstallExecutionError::new(error.to_string()),
                )
                .await,
            );
        }
    };
    let admin_outcome = match ports
        .provision_admin(&database.runtime, &plan, seed_outcome.tenant_id, &password)
        .await
    {
        Ok(outcome) => outcome,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::RecoveryRequired,
                    error,
                )
                .await,
            );
        }
    };
    let admin = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Admin,
        &snapshot,
        serde_json::json!({
            "tenant_id": seed_outcome.tenant_id,
            "admin_email": admin_outcome.email,
            "admin_user_id": admin_outcome.user_id,
            "admin_created": admin_outcome.created,
            "role": "super_admin"
        }),
    )
    .await?;
    session = ports
        .set_state(
            &database.runtime,
            &session,
            InstallState::AdminProvisioned,
        )
        .await?;
    let output = match crate::execute_distribution_deployment(
        ports,
        &database.runtime,
        &plan,
        session.clone(),
        seed_outcome.tenant_id,
    )
    .await
    {
        Ok(out) => out,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::RecoveryRequired,
                    error,
                )
                .await,
            );
        }
    };
    session = output.session;
    let deployment_receipt = output.receipt;
    let verify_outcome = match ports
        .verify_installation(&database.runtime, &plan, seed_outcome.tenant_id)
        .await
    {
        Ok(outcome) => outcome,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::RecoveryRequired,
                    error,
                )
                .await,
            );
        }
    };
    let verify = record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Verify,
        &snapshot,
        serde_json::json!({
            "tenant_id": verify_outcome.tenant_id,
            "tenant_slug": verify_outcome.tenant_slug,
            "admin_user_id": verify_outcome.admin_user_id,
            "enabled_modules": verify_outcome.enabled_modules
        }),
    )
    .await?;
    session = ports
        .set_state(&database.runtime, &session, InstallState::Verified)
        .await?;
    let finalize = match record_success(
        ports,
        &database.runtime,
        &session,
        InstallStep::Finalize,
        &snapshot,
        serde_json::json!({
            "completed": true,
            "tenant_id": verify_outcome.tenant_id,
            "tenant_slug": verify_outcome.tenant_slug
        }),
    )
    .await
    {
        Ok(fin) => fin,
        Err(error) => {
            return Err(
                persist_failure_state(
                    ports,
                    &database.runtime,
                    &session,
                    InstallState::RecoveryRequired,
                    error,
                )
                .await,
            );
        }
    };
    session = ports
        .set_state(&database.runtime, &session, InstallState::Completed)
        .await?;

    Ok(InstallApplyOutput {
        status: "completed".to_string(),
        session_id: session.id,
        tenant_id: session.tenant_id,
        lock_owner: session.lock_owner,
        lock_expires_at: session.lock_expires_at,
        preflight_receipt_id: preflight.id,
        preflight_receipt_checksum: preflight.input_checksum,
        config_receipt_id: config.id,
        config_receipt_checksum: config.input_checksum,
        database_receipt_id: database_receipt.id,
        database_receipt_checksum: database_receipt.input_checksum,
        migrate_receipt_id: migrate.id,
        migrate_receipt_checksum: migrate.input_checksum,
        seed_receipt_id: seed.id,
        seed_receipt_checksum: seed.input_checksum,
        admin_receipt_id: admin.id,
        admin_receipt_checksum: admin.input_checksum,
        verify_receipt_id: verify.id,
        verify_receipt_checksum: verify.input_checksum,
        finalize_receipt_id: finalize.id,
        finalize_receipt_checksum: finalize.input_checksum,
        deployment_receipt,
        next: None,
    })
}

#[cfg(feature = "host-runtime")]
async fn persist_failure_state<P>(
    ports: &P,
    runtime: &P::Runtime,
    session: &InstallSessionRecord,
    target: InstallState,
    cause: InstallExecutionError,
) -> InstallExecutionError
where
    P: InstallDatabasePort + InstallPersistencePort<P::Runtime>,
{
    match ports.set_state(runtime, session, target).await {
        Ok(_) => cause,
        Err(persistence_error) => InstallExecutionError::new(format!(
            "{cause}; failed to persist installer state {target:?} for attempt generation {}: {persistence_error}",
            session.attempt_generation
        )),
    }
}

#[cfg(feature = "host-runtime")]
async fn record_success<P>(
    ports: &P,
    runtime: &P::Runtime,
    session: &InstallSessionRecord,
    step: InstallStep,
    snapshot: &serde_json::Value,
    diagnostics: serde_json::Value,
) -> Result<InstallReceiptRecord, InstallExecutionError>
where
    P: InstallDatabasePort + InstallPersistencePort<P::Runtime>,
{
    let receipt = InstallReceipt::success(session.id.to_string(), step, snapshot, diagnostics)
        .map_err(|error| InstallExecutionError::new(error.to_string()))?;
    ports.record_receipt(runtime, session, &receipt).await
}

#[derive(Debug, Error)]
#[error("install execution failed: {message}")]
pub struct InstallExecutionError {
    message: String,
}

impl InstallExecutionError {
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}
